"""Markdown and JSON report helpers."""

from app.models.schemas import ResonanceReport
from app.services.one_pager import build_one_pager


def to_markdown(report: ResonanceReport) -> str:
    """Render a ResonanceReport as a professional Markdown document."""
    d = report.diagnosis
    a = report.architecture
    g = report.generated_code
    c = report.critique

    lines: list[str] = []
    # Leadership brief first
    lines.append(build_one_pager(report).rstrip())
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("# ResonanceForge Assessment Report")
    lines.append("")
    lines.append("## Question")
    lines.append("")
    lines.append(report.user_question)
    lines.append("")

    lines.append("## Diagnosis (ACCESS / ADAPT / ADOPT)")
    lines.append("")
    lines.append(f"**Overall readiness:** {d.overall_readiness}")
    lines.append("")
    lines.append("| Dimension | Score | Reason |")
    lines.append("|-----------|------:|--------|")
    lines.append(f"| ACCESS | {d.access.score}/10 | {d.access.reason} |")
    lines.append(f"| ADAPT | {d.adapt.score}/10 | {d.adapt.reason} |")
    lines.append(f"| ADOPT | {d.adopt.score}/10 | {d.adopt.reason} |")
    lines.append("")
    lines.append("### Top gaps")
    lines.append("")
    for gap in d.top_gaps:
        lines.append(f"- {gap}")
    lines.append("")
    lines.append("### Summary")
    lines.append("")
    lines.append(d.summary)
    lines.append("")

    lines.append("## Architecture")
    lines.append("")
    lines.append(f"**Estimated complexity:** {a.estimated_complexity}")
    lines.append("")
    lines.append("### Recommended agents")
    lines.append("")
    for agent in a.recommended_agents:
        lines.append(f"- **{agent.name}** — {agent.responsibility}")
    lines.append("")
    lines.append("### High-level flow")
    lines.append("")
    for i, step in enumerate(a.high_level_flow, 1):
        lines.append(f"{i}. {step}")
    lines.append("")
    lines.append("### Rationale")
    lines.append("")
    lines.append(a.rationale)
    lines.append("")

    lines.append("## Generated LangGraph Code")
    lines.append("")
    lines.append(g.explanation)
    lines.append("")
    lines.append("```python")
    lines.append(g.code.rstrip())
    lines.append("```")
    lines.append("")

    lines.append("## Critique")
    lines.append("")
    lines.append(f"**Final verdict:** {c.final_verdict}")
    lines.append("")
    lines.append("### Strengths")
    lines.append("")
    for item in c.strengths:
        lines.append(f"- {item}")
    lines.append("")
    lines.append("### Weaknesses")
    lines.append("")
    for item in c.weaknesses:
        lines.append(f"- {item}")
    lines.append("")
    lines.append("### Risks")
    lines.append("")
    for item in c.risks:
        lines.append(f"- {item}")
    lines.append("")
    lines.append("### Recommendations")
    lines.append("")
    for item in c.recommendations:
        lines.append(f"- {item}")
    lines.append("")
    if report.evidence:
        lines.extend(evidence_markdown(report))
    lines.append("---")
    lines.append("*Generated by ResonanceForge v1*")
    lines.append("")

    return "\n".join(lines)


def evidence_markdown(report: ResonanceReport) -> list[str]:
    """Evidence section: the customer passages agents were shown, and which were cited."""
    ev = report.evidence
    if ev is None:
        return []
    lines = ["## Evidence", ""]
    docs = ", ".join(f"{d.label} = {d.filename}" for d in ev.documents) or "none"
    lines.append(f"Customer documents: {docs}")
    lines.append("")
    if not ev.passages:
        lines.append("No passages matched this assessment.")
        lines.append("")
        return lines
    cited = sum(1 for p in ev.passages if p.cited)
    lines.append(
        f"{len(ev.passages)} passages retrieved (BM25), {cited} cited. "
        f"Unverified citations removed: {ev.citations_dropped}."
    )
    lines.append("")
    for p in ev.passages:
        tag = "cited" if p.cited else "retrieved, not cited"
        snippet = " ".join(p.text.split())
        if len(snippet) > 400:
            snippet = snippet[:397] + "..."
        lines.append(f"- **[{p.ref}]** {p.document}, chunk {p.chunk} ({tag}; {', '.join(p.used_by)})")
        lines.append(f"  > {snippet}")
    lines.append("")
    return lines
